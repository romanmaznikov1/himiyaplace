/**
 * Мини-типограф для русского текста: не даёт «висеть» предлогам и союзам в конце строки
 * и переносить тире на новую строку.
 *
 *   ty("Покупать абонемент после пробного не обязательно") → «не» склеено с «обязательно»
 *   <p>{ty("Напиши в Telegram или позвони — подскажем")}</p>
 *
 * Только для текста абзацев. Не применяйте к строкам, которые потом режутся по пробелу
 * (адрес, имя, заголовки MotionBlurTitle).
 */
const NBSP = "\u00A0";

/** Короткие слова (1–2 буквы) + частые трёхбуквенные предлоги/союзы — приклеиваются к следующему слову. */
const SHORT = /(^|[\s(«„"'—–-])([а-яёА-ЯЁa-zA-Z]{1,2}|для|без|под|над|при|про|из-за|или|что|как)\s+/g;
/** Частицы — приклеиваются к предыдущему слову. */
const PARTICLE = /\s+(же|ли|ль|бы|б)(?=[\s.,!?;:…)»]|$)/g;
/** Тире не начинает строку. */
const DASH = /\s+([—–])/g;
/** Число и единица/знак: «17 лет», «350 ₽», «60 минут». */
const NUM_UNIT = /(\d)\s+(?=[а-яёА-ЯЁ₽%]|руб)/g;
/** Инициалы и сокращения «просп. Кулакова»: точка + пробел перед словом с заглавной. */
const ABBR = /(^|\s)(просп|ул|пр|д|г|им|т\.е|т\.к)\.\s+/g;

export function ty(text: string): string {
  let s = text;
  // дважды — для цепочек «и в», «а то и»
  s = s.replace(SHORT, (_, pre: string, word: string) => `${pre}${word}${NBSP}`);
  s = s.replace(SHORT, (_, pre: string, word: string) => `${pre}${word}${NBSP}`);
  s = s.replace(PARTICLE, `${NBSP}$1`);
  s = s.replace(DASH, `${NBSP}$1`);
  s = s.replace(NUM_UNIT, `$1${NBSP}`);
  s = s.replace(ABBR, (_, pre: string, a: string) => `${pre}${a}.${NBSP}`);
  return s;
}
